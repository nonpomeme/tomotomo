// 教材の調査・生成・検証に使う指示文。サンプル3テーマ（組織論のお手本）を「形式と品質の基準」として渡す。
// 題材はカリキュラム（content/curriculum.json）の単元。ニュースの選定は行わない（要件 GN-1）。
export function commonContext(A) {
  const nodes = Object.fromEntries(Object.entries(A.NODES).map(([k, n]) => [k, n.name + '／' + n.cat + '／' + n.sub]));
  return [
    '# TomoTomo の教材について',
    'TomoTomo は、採用・組織づくりに関わる社会人が、組織論を学術的かつ実践的に学ぶアプリ。ユーザーは毎日10〜15分で「知る→理解する→解く→考える→言語化する→仕事に応用する」を行う。',
    '教材は組織論のカリキュラム（12章・37単元）の1単元を扱う。研究（査読付き論文・メタ分析・古典）と公的統計を根拠にし、事実とAIの解釈を分ける。',
    '以下のサンプル3テーマが教材の形式と品質の基準（お手本）。新しい教材はこれと同じ JSON 形式・同じ深さ・同じ文体で作る。サンプルの内容（テーマや文章）は真似しない。',
    '',
    '## 使える値',
    '- skill（問題で鍛える力）: ' + JSON.stringify(A.SKILLS),
    '- 知識マップのカテゴリ（cat、組織論の5分野）: ' + JSON.stringify(Object.keys(A.MAP_CATS)),
    '- 既存の知識ノード（id: 名前／カテゴリ／小分類）: ' + JSON.stringify(nodes),
    '- 線の種類（関係）: ' + JSON.stringify(A.REL_LABEL),
    '- industries に使える業界: ' + JSON.stringify(A.INDUSTRIES),
    '- tags に使える値: ' + JSON.stringify(A.INTEREST_OPTIONS),
    '',
    '## サンプル3テーマ（JSON）',
    JSON.stringify(A.TOPICS)
  ].join('\n');
}

