// 教材の選定・生成・検証に使う指示文。サンプル3テーマを「形式と品質の基準」として渡す。
export function commonContext(A) {
  const nodes = Object.fromEntries(Object.entries(A.NODES).map(([k, n]) => [k, n.name + '／' + n.cat + '／' + n.sub]));
  return [
    '# TomoTomo の教材について',
    'TomoTomo は社会人向けの教養トレーナー。ユーザーは毎日10〜15分で「知る→理解する→解く→考える→言語化する→仕事に応用する」を行う。',
    '以下のサンプル3テーマが教材の形式と品質の基準（お手本）。新しい教材はこれと同じ JSON 形式・同じ深さ・同じ文体で作る。サンプルの内容（テーマや文章）は真似しない。',
    '',
    '## 使える値',
    '- skill（問題で鍛える力）: ' + JSON.stringify(A.SKILLS),
    '- 知識マップのカテゴリ（cat）: ' + JSON.stringify(Object.keys(A.MAP_CATS)),
    '- 既存の知識ノード（id: 名前／カテゴリ／小分類）: ' + JSON.stringify(nodes),
    '- 線の種類（関係）: ' + JSON.stringify(A.REL_LABEL),
    '- industries に使える業界: ' + JSON.stringify(A.INDUSTRIES),
    '- tags に使える値: ' + JSON.stringify(A.INTEREST_OPTIONS.concat(['最新ニュース'])),
    '',
    '## サンプル3テーマ（JSON）',
    JSON.stringify(A.TOPICS)
  ].join('\n');
}

/* 選定の指示。T は tracks.json、track は今日のトラック（なければ全トラックから） */
export function selectSystem(T, track) {
  const list = Object.entries(T.tracks).map(([k, t]) => '- ' + t.label + '：' + t.focus).join('\n');
  return [
    'あなたは TomoTomo の編集者です。読者は ' + T.audience + '。',
    '公的機関・企業の公式発表の新着一覧から、今日の教材にするものを選びます。',
    track ? '今日のテーマは「' + track.label + '」：' + track.focus + '。このテーマに合うものを最優先で選んでください。' : '今日のテーマに合う候補がなかったため、次のテーマのいずれかに合うものを選んでください。',
    '',
    '## テーマ一覧', list, '',
    '## 選ぶ基準（すべて満たすもの）',
    '1. テーマ一覧のいずれかの分野で、社会人が仕事の判断に使える専門知識（仕組み・数字・制度の要件・手法の違い・業界構造・判断の基準）を引き出せる、具体的な中身がある。どの業界にも言える一般論にしかならないものは選ばない。',
    '2. 発表を入り口に、公的機関などの資料を調べて掘り下げる価値がある（制度・統計・業界構造などの背景知識につながる）。',
    '3. 政治的な対立が中心の話題（選挙・特定の政党や政治家の主張など）ではない。',
    '4. 人事異動・入札・行事の告知・単なる商品の宣伝・キャンペーンではない。',
    '5. 直近に配信したテーマと重ならない。',
    '基準を満たすものがなければ picks を空にする。無理に選ばない。'
  ].join('\n');
}

