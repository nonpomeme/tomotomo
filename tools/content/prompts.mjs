/* 単元の説明（調査・生成・検査で共通） */
export function unitBrief(ch, u, seeds) {
  return [
    '# 今日の単元',
    '- 章：' + ch.title + '（分野：' + ch.cat + '）',
    '- 章の役割：' + ch.role,
    '- 単元：' + u.id + '　' + u.title,
    '- 鍵になる概念：' + u.concepts.join('、'),
    '- 単元の出典（カリキュラムの調査で書誌と内容を確認済み。事実の根拠の中心にする）:',
    ...seeds.map(s => '  - [' + s.rank + '・' + s.kind + '] ' + s.cite + ' ' + s.url + '\n    確認した内容：' + s.finding)
  ].join('\n');
}

